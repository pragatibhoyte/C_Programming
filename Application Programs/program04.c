void ChkEvenOdd(int iNo)
{
    int iRemainder = 0;

    iRemainder = iNo % 2;

    if(iRemainder == 0)
    {
        printf("%d is Even\n",iNo);
    }
    else
    {
        printf("%d is Odd\n",iNo);
    }
}

int main()
{
    int iValue = 0;

    printf("Enter Number : \n");
    scanf("%d",&iValue);

    ChkEvenOdd(iValue);
}

